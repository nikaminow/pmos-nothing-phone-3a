"""Full RAM map for our DTB from ABL's own DT (abl.dts, decompiled from the DTB ABL hands to
Android): its memory node (all usable DDR, ~7.6 GiB; our DT had only the 4 GiB bank at
0x9_0000_0000) and every static, non-reusable reserved-memory region ABL keeps inside it, so Linux
never touches firmware carve-outs that mainline milos.dtsi does not know about.
Prints a dts fragment: abl-memmap.py abl.dts > abl-memmap.dtsi"""
import re, sys

src = open(sys.argv[1]).read()


def cells(s):
    return [int(x, 16) for x in s.split()]


def pairs(v):
    return [((v[i] << 32) | v[i + 1], (v[i + 2] << 32) | v[i + 3]) for i in range(0, len(v), 4)]


mem = pairs(cells(re.search(r'\n\tmemory \{[^}]*?reg = <([^>]*)>', src).group(1)))
mem.sort()
rm = src[src.index('reserved-memory {'):]
# top-level children of /reserved-memory: name { ... reg = <...>; ... };
res = []
depth, i = 0, rm.index('{') + 1
start = None
for m in re.finditer(r'([\w,.@-]+) \{|\};', rm[i:]):
    if m.group(0) == '};':
        depth -= 1
        if depth < 0:
            break
        if depth == 0:
            body = rm[i + start:i + m.end()]
            r = re.search(r'\breg = <([^>]*)>', body)
            if r and 'reusable' not in body:
                name = body.split(' {')[0].strip()
                for a, s in pairs(cells(r.group(1))):
                    res.append((name, a, s))
    else:
        if depth == 0:
            start = m.start()
        depth += 1


def in_ram(a, s):
    return any(a < b + l and b < a + s for b, l in mem)


print('/* generated by abl-memmap.py from abl.dts: ABL memory map + its static carve-outs */')
print('/ {')
print('\tmemory@80000000 {')
print('\t\tdevice_type = "memory";')
print('\t\treg = ' + ',\n\t\t      '.join('<0x%x 0x%08x 0x%x 0x%08x>' % (a >> 32, a & 0xffffffff, s >> 32, s & 0xffffffff) for a, s in mem) + ';')
print('\t};')
print('')
print('\treserved-memory {')
n = 0
for name, a, s in res:
    if not in_ram(a, s):
        continue
    print('\t\tabl-%02d-%s {' % (n, re.sub(r'@.*', '', name)))
    print('\t\t\treg = <0x%x 0x%08x 0x%x 0x%08x>;' % (a >> 32, a & 0xffffffff, s >> 32, s & 0xffffffff))
    print('\t\t\tno-map;')
    print('\t\t};')
    n += 1
print('\t};')
print('};')
total = sum(s for _, s in mem)
print('/* RAM %.2f GiB in %d ranges, %d ABL carve-outs inside it */' % (total / 2**30, len(mem), n), file=sys.stderr)
